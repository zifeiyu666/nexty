export function useWizardCopy(): WizardCopy {
  const locale = useLocale();
  if (locale === "es") return spanish;
  if (locale === "ja") return japanese;
  return english;
}

export function useWizardLocale() {
  const locale = useLocale();
  return locale === "es" || locale === "ja" ? locale : "en";
}

export function localizedOccasionLabel(locale: string, value: string, fallback: string) {
  return occasionLabels[locale]?.[value] || fallback;
}

export function localizedGenreLabel(locale: string, value: string, fallback: string) {
  return genreLabels[locale]?.[value] || fallback;
}

export function localizedRelationshipLabel(
  locale: string,
  value: string,
  fallback: string,
) {
  return relationshipLabels[locale]?.[value] || fallback;
}

export function getLocalizedRelationshipOptions(locale: string, query = "") {
  const normalizedQuery = query.trim().toLocaleLowerCase(locale);

  return relationshipOptions
    .map((value) => ({
      value,
      label: localizedRelationshipLabel(locale, value, value),
    }))
    .filter(({ label, value }) => {
      if (!normalizedQuery) return true;

      return (
        label.toLocaleLowerCase(locale).includes(normalizedQuery) ||
        value.toLocaleLowerCase("en").includes(normalizedQuery)
      );
    });
}

